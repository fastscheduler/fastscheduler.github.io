# -*- coding: utf-8 -*-
"""Emit tools/ru_batches/help_11_setup_rbac.py from tools/help_v2_ru.py.

The Russian help site is built from tools/ru_batches/help_*.py, while the bot
reads translations/ru.json. The sender-first / RBAC rewrite lives in
tools/help_v2_ru.py (one source, three languages), so the Russian batch is
generated from it instead of being retyped: the two copies cannot drift.

Why a generator and not a hand-written batch: 17 articles, and every one of
them carries wiki links ([[id|text]]) that tools/build_ru.py does not resolve —
it only wraps them in a placeholder span, which would ship "[[" to readers.
The generator turns each link into a real relative <a href> so the Russian
pages keep the same internal linking as the English ones.

Run from the repo root after editing tools/help_v2_ru.py:

    python tools/make_ru_setup_batch.py           # write the batch
    python tools/make_ru_setup_batch.py --check   # report only
"""

import io
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from help_v2_ru import CONTENT_RU  # noqa: E402

OUT = os.path.join(HERE, 'ru_batches', 'help_11_setup_rbac.py')

WIKI = re.compile(r'\[\[([a-z0-9_]+)\|([^\]]+)\]\]')


def relink(text):
    """[[id|слова]] -> <a href="id.html">слова</a> (same directory as the page)."""
    if not isinstance(text, str):
        return text
    text = WIKI.sub(lambda m: '<a href="%s.html">%s</a>' % (m.group(1), m.group(2)), text)
    # A bare [[id]] would be a missing label — fail loudly instead of shipping it.
    if '[[' in text or ']]' in text:
        raise SystemExit('unresolved wiki link left in: %r' % text[:80])
    return text


def py(value, indent=1):
    """Pretty-print a python literal with stable ordering."""
    pad = '    ' * indent
    if isinstance(value, dict):
        inner = ',\n'.join('%s    %r: %s' % (pad, k, py(v, indent + 1)) for k, v in value.items())
        return '{\n%s,\n%s}' % (inner, pad) if inner else '{}'
    if isinstance(value, list):
        inner = ',\n'.join('%s    %s' % (pad, py(v, indent + 1)) for v in value)
        return '[\n%s,\n%s]' % (inner, pad) if inner else '[]'
    return repr(value)


def build_batch():
    patch = {}
    for aid in sorted(CONTENT_RU):
        rec = CONTENT_RU[aid]
        entry = {
            'title': rec.get('title', ''),
            'content': relink(rec.get('content', '')),
        }
        desc = rec.get('description')
        if desc:
            entry['description'] = relink(desc)
        faq = []
        for item in rec.get('faq') or []:
            if not isinstance(item, dict):
                continue
            row = {'q': relink(item.get('q', '')), 'a': relink(item.get('a', ''))}
            if item.get('links'):
                row['links'] = list(item['links'])
            faq.append(row)
        if faq:
            entry['faq'] = faq
        patch[aid] = entry
    return patch


def main(argv):
    patch = build_batch()
    header = (
        '# -*- coding: utf-8 -*-\n'
        '"""RU help batch 11: sender-bot-first setup and the RBAC rewrite.\n\n'
        'GENERATED by tools/make_ru_setup_batch.py from tools/help_v2_ru.py — do not\n'
        'edit by hand; edit the source and re-run the generator. Covers %d articles:\n'
        '%s.\n"""\n\n'
        'PATCH = %s\n'
    ) % (len(patch), ', '.join(sorted(patch)), py(patch))
    if '--check' in argv:
        print('batch would contain %d articles: %s' % (len(patch), ', '.join(sorted(patch))))
        if os.path.exists(OUT):
            with io.open(OUT, encoding='utf-8') as f:
                same = f.read() == header
            print('on-disk batch is %s' % ('identical' if same else 'STALE — re-run without --check'))
        return
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with io.open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(header)
    print('wrote %s (%d articles)' % (os.path.relpath(OUT, os.path.dirname(HERE)), len(patch)))


if __name__ == '__main__':
    main(sys.argv[1:])
